const eventTimeFormatters = new Map();
function getTimeZoneFormatter(timeZone) {
  // Accept named IANA identifiers only, never numeric UTC offsets.
  if (typeof timeZone !== "string" || !timeZone.includes("/") || /^Etc\/GMT[+-]/.test(timeZone)) return null;
  try {
    if (!eventTimeFormatters.has(timeZone)) eventTimeFormatters.set(timeZone, new Intl.DateTimeFormat("en-GB", {
      timeZone, year: "numeric", month: "2-digit", day: "2-digit",
      hour: "2-digit", minute: "2-digit", second: "2-digit", hourCycle: "h23"
    }));
    return eventTimeFormatters.get(timeZone);
  } catch { return null; }
}

function getZonedTimeParts(timestamp, formatter) {
  return Object.fromEntries(formatter.formatToParts(new Date(timestamp))
    .filter(part => part.type !== "literal").map(part => [part.type, Number(part.value)]));
}

function zonedPartsTimestamp(parts) {
  return Date.UTC(parts.year, parts.month - 1, parts.day, parts.hour, parts.minute, parts.second);
}

// Resolve a local wall-clock time using offsets derived from Intl on the surrounding dates.
// Nonexistent or repeated DST wall-clock times have no unique instant: leave them unconverted.
function localTimeToInstant(dateTimestamp, hour, minute, formatter) {
  const wallTime = dateTimestamp + (hour * 60 + minute) * 60000;
  const offsets = new Set();
  for (const hours of [-36, -12, 0, 12, 36]) {
    const probe = wallTime + hours * 3600000;
    offsets.add(zonedPartsTimestamp(getZonedTimeParts(probe, formatter)) - probe);
  }
  const candidates = [...offsets].map(offset => wallTime - offset)
    .filter(instant => zonedPartsTimestamp(getZonedTimeParts(instant, formatter)) === wallTime);
  return candidates.length === 1 ? candidates[0] : null;
}

function parseEventDate(value) {
  const match = typeof value === "string" && value.match(/^(\d{4})-(\d{2})-(\d{2})$/);
  if (!match) return null;
  const [, year, month, day] = match.map(Number);
  const timestamp = Date.UTC(year, month - 1, day);
  const date = new Date(timestamp);
  return date.getUTCFullYear() === year && date.getUTCMonth() === month - 1 && date.getUTCDate() === day ? timestamp : null;
}

function getEventJapanTimes(event) {
  const venue = getEventVenue(event);
  const country = venue?.country || event.cityCountry?.split(/[/／]/)[1]?.trim();
  const timeZone = event.timeZone || venue?.timeZone;
  if (country === "日本" || timeZone === "Asia/Tokyo" ||
    (event.region !== "海外" && event.conferenceRegion !== "international")) return [];
  const formatter = getTimeZoneFormatter(timeZone);
  const japanFormatter = getTimeZoneFormatter("Asia/Tokyo");
  const time = typeof event.time === "string" && event.time.match(/^\s*(\d{1,2}):(\d{2})\s*[-–〜～]\s*(\d{1,2}):(\d{2})(?:\s*[（(]現地時間[）)])?\s*$/);
  const startDate = parseEventDate(event.date);
  const endDate = parseEventDate(event.endDate || event.date);
  if (!formatter || !time || startDate === null || endDate === null || endDate < startDate || endDate - startDate > 366 * 86400000) return [];
  const [, startHour, startMinute, endHour, endMinute] = time.map(Number);
  if (startHour > 23 || startMinute > 59 || endHour > 24 || endMinute > 59 || (endHour === 24 && endMinute !== 0)) return [];
  const rows = [];
  for (let date = startDate; date <= endDate; date += 86400000) {
    const overnight = endHour * 60 + endMinute < startHour * 60 + startMinute;
    const start = localTimeToInstant(date, startHour, startMinute, formatter);
    const end = localTimeToInstant(date + (overnight ? 86400000 : 0), endHour, endMinute, formatter);
    if (start === null || end === null || end < start) return [];
    const label = instant => {
      const parts = getZonedTimeParts(instant, japanFormatter);
      const dayDifference = (Date.UTC(parts.year, parts.month - 1, parts.day) - date) / 86400000;
      const prefix = dayDifference === 0 ? "" : dayDifference === 1 ? "翌" : dayDifference === -1 ? "前日" :
        dayDifference > 0 ? `${dayDifference}日後 ` : `${-dayDifference}日前 `;
      return `${prefix}${String(parts.hour).padStart(2, "0")}:${String(parts.minute).padStart(2, "0")}`;
    };
    rows.push({ date: new Date(date).toISOString().slice(0, 10), text: `${label(start)} - ${label(end)}（日本時間）` });
  }
  return rows;
}

function getEventVenue(event) {
  return Object.hasOwn(venueMaster, event.venueId) ? venueMaster[event.venueId] : null;
}

// イベント固有の部屋名や配信併記を保持する。
function getEventVenueName(event) {
  return event.venue || getEventVenue(event)?.name || "";
}

// Display only: classification, region labels and Maps queries retain their existing rules.
function getEventCityDisplay(event) {
  const cityCountry = typeof event.cityCountry === "string" ? event.cityCountry.trim() : "";
  const [city, legacyCountry] = cityCountry.split(/[/／]/).map(part => part.trim());
  const country = getEventVenue(event)?.country?.trim() || legacyCountry;
  const domestic = country === "日本" || (!country && event.region && event.region !== "海外");
  return {
    label: domestic ? "開催都市" : "開催都市・国",
    value: (domestic ? city : cityCountry) || getEventVenueName(event)
  };
}

// 表示専用。フィルターや学会分類に使う region / conferenceRegion は変更しない。
function getEventVenueRegionLabel(event) {
  const masterCountry = getEventVenue(event)?.country;
  const legacyCountry = typeof event.cityCountry === "string"
    ? event.cityCountry.split(/[/／]/)[1]?.trim()
    : "";
  const country = (typeof masterCountry === "string" && masterCountry.trim()) || legacyCountry;
  const region = event.region || "";
  if (country === "日本") return region === "海外" ? "国内" : region;
  if (region !== "海外" && event.conferenceRegion !== "international") return region;
  // 地域名や未確認の文字列を国名として表示しない。
  if (!country || /未定|要確認|不明/.test(country) || ["欧州", "アジア", "海外"].includes(country)) {
    return region;
  }
  return country === "シンガポール共和国" ? "シンガポール" : country;
}
