const assert = require('node:assert/strict');
const {loadEvents} = require('../scripts/auto-updater/storage');
const {text,extractOfficialHtml} = require('../scripts/auto-updater/extract');
const {extractVenueSection,venuesFromLocations,validVenues} = require('../scripts/auto-updater/venues');
const {assess,setField,applyChanges} = require('../scripts/auto-updater/policy');
const {extractMonitoringContext} = require('../scripts/gemini-monitor/extractor');
const {classifyDecision} = require('../scripts/gemini-monitor/classifier');
const {applyFieldChangesToEvent} = require('../scripts/gemini-monitor/applier');
const config = require('../conference-sources');
const model = require('../review-model');
const root = require('node:path').resolve(__dirname,'..');
for(const id of ['oph-001','conf-jp-ringan-2027','oph-011','conf-jp-jos-2028']) {
  const event=loadEvents(root).events.find(e=>e.id===id);
  // Official-style venue/individual address blocks, scoped to the current edition.
  const section=event.venues.map(v=>`${v.name}<br>〒100-0005 東京都千代田区丸の内1-1`).join('<br>');
  const html=`<title>${event.title}</title><dl><dt>会場</dt><dd>${section}</dd></dl>`;
  const url='https://official.example/overview.html';
  const source={id,year:Number(event.date.slice(0,4)),identity:[event.title],allowedHosts:['official.example'],pages:[{url,role:'overview'}]};
  const extracted=extractOfficialHtml({html,url,role:'overview'},source);
  const candidate=extracted.candidates.find(c=>c.field==='venues');
  assert.ok(candidate,id);assert.ok(!extracted.candidates.some(c=>c.field==='venue'));
  assert.ok(!extracted.issues.includes('venue-unextractable'));
  assert.deepEqual(candidate.value.map(v=>v.name),event.venues.map(v=>v.name.normalize('NFKC')));
  assert.equal(new Set(candidate.value.map(v=>v.mapUrl)).size,event.venues.length);
  for(const v of candidate.value)assert.ok(new URL(v.mapUrl).searchParams.get('query').includes(v.name));
  const decision=assess({...event,venues:undefined},source,[candidate],[],config.defaults,{today:'2026-10-14'});
  assert.equal(decision.accepted.length,0);assert.equal(decision.review[0].reason,'multiple-venues-needs-review');
  const review=model.normalize({items:[{...decision.review[0],eventId:id}]})[0];
  assert.ok(review.actionable);assert.ok(model.formatValue('venues',candidate.value).includes(candidate.value[0].name));
  const target=structuredClone(event);setField(target,'venues',candidate.value);assert.equal(target.venue,event.venue);
  assert.throws(()=>applyChanges([event],[{...candidate,eventId:id}]),/manual review/);
  const context=extractMonitoringContext(html,event);
  assert.deepEqual(context.multipleVenueCandidates,[candidate.value]);
  const classification=classifyDecision({...event,venues:undefined},{same_event:true,source_quality:'official_event_page',confidence:1,venue:'joined guess'}, {officialVenues:candidate.value});
  assert.equal(classification.isAutoApplicable,false);assert.ok(classification.fieldChanges.some(c=>c.field==='venues'));
  assert.ok(!classification.fieldChanges.some(c=>c.field==='venue'));
  applyFieldChangesToEvent(target,[{field:'venue',after:'wrong'},{field:'venues',after:candidate.value}]);
  assert.equal(target.venue,event.venue);
}
